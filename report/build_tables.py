"""Build report tables directly from the published, paired benchmark evidence."""

import csv
import hashlib
import json
from collections import defaultdict
from decimal import Decimal
from pathlib import Path
from statistics import median

REPORT = Path(__file__).resolve().parent
ROOT = REPORT.parent
DATA = ROOT / "docs" / "benchmarks"


def main():
    with (DATA / "2026-10-22.csv").open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    manifest = json.loads((DATA / "2026-10-22-manifest.json").read_text())
    if len(rows) != 90 or len(manifest["runs"]) != len(rows):
        raise ValueError("Expected the published 90-run baseline")
    if any(row["status"] != "solved" for row in rows):
        raise ValueError("This baseline's tables expect successful runs only")
    actual_hash = hashlib.sha256(
        b"".join(
            path.name.encode() + path.read_bytes()
            for path in sorted((ROOT / "pipes_problem").glob("*.py"))
            if not path.name.startswith("test_")
        )
    ).hexdigest()
    if actual_hash != manifest["environment"]["source_sha256"]:
        raise ValueError("Solver changed: update the report's benchmark evidence")

    by_map = defaultdict(list)
    by_size = defaultdict(list)
    for number, (row, run) in enumerate(zip(rows, manifest["runs"]), 1):
        if run["csv_row"] != number:
            raise ValueError("Manifest rows do not match the CSV")
        record = {
            "time": Decimal(row["time_ms"]),
            "memory": Decimal(row["peak_memory_kib"]),
            "expanded": run["expanded"],
        }
        by_map[row["algorithm"], row["puzzle_id"]].append(record)
        by_size[row["algorithm"], int(row["grid_size"])].append(record)

    output = REPORT / "generated"
    output.mkdir(exist_ok=True)
    header = "% Generated by report/build_tables.py from the published CSV/manifest.\n"
    for algorithm, label, filename in (
        ("dfs", "DFS", "dfs-table.tex"),
        ("greedy_best_first", "GBFS", "greedy-table.tex"),
    ):
        lines = [
            header,
            r"\begin{table}[H]\centering\small",
            r"\begin{tabular}{@{}lrrrr@{}}\toprule",
            r"Bản đồ & $n$ & Thời gian (ms) & Đỉnh (KiB) & Mở rộng\\\midrule",
        ]
        for (name, identity), values in sorted(by_map.items()):
            if name != algorithm:
                continue
            if len(values) != 5 or len({v["expanded"] for v in values}) != 1:
                raise ValueError("Expected five deterministic repetitions per input")
            _, dimensions, suffix = identity.split("-")
            size = int(dimensions.split("x")[0])
            lines.append(
                f"{dimensions}-{suffix} & {size * size} & "
                f"{median(v['time'] for v in values):.4f} & "
                f"{median(v['memory'] for v in values):.3f} & "
                f"{values[0]['expanded']} \\\\"
            )
        lines.extend(
            [
                r"\bottomrule\end{tabular}",
                "\\caption{"
                + label
                + ": trung vị theo từng bản đồ trên 5 lượt thành công. "
                "Tên rút gọn 4x4-261 tương ứng pipes-4x4-261.json.}",
                r"\end{table}",
            ]
        )
        (output / filename).write_text("\n".join(lines) + "\n", encoding="utf-8")

    summary = {}
    for (algorithm, size), values in by_size.items():
        if len(values) != 15:
            raise ValueError("Expected 15 successful runs per size and algorithm")
        summary[algorithm, size] = {
            key: median(value[key] for value in values) for key in ("time", "memory")
        }
    lines = [
        header,
        r"\begin{table}[H]\centering\small",
        r"\begin{tabular}{@{}lrrrrr@{}}\toprule",
        r" & \multicolumn{2}{c}{Thời gian (ms)} & GBFS/DFS & \multicolumn{2}{c}{Đỉnh (KiB)}\\",
        r"Cỡ & DFS & GBFS & thời gian & DFS & GBFS\\\midrule",
    ]
    for size in (4, 5, 7):
        dfs, greedy = summary["dfs", size], summary["greedy_best_first", size]
        lines.append(
            f"${size}\\times{size}$ & {dfs['time']:.3f} & {greedy['time']:.3f} & "
            f"{greedy['time'] / dfs['time']:.2f} & {dfs['memory']:.3f} & "
            f"{greedy['memory']:.3f} \\\\"
        )
    lines.extend(
        [
            r"\bottomrule\end{tabular}",
            (
                r"\caption{Trung vị trên 15 lượt thành công mỗi cỡ và thuật toán. "
                r"Tỷ lệ lớn hơn 1 nghĩa là GBFS chậm hơn DFS.}"
            ),
            r"\end{table}",
        ]
    )
    (output / "comparison-table.tex").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )

    lines = [header]
    for key, ylabel in (("time", "Thời gian (ms)"), ("memory", "Đỉnh cấp phát (KiB)")):
        lines.extend(
            [
                r"\begin{tikzpicture}",
                r"\begin{axis}[width=.48\textwidth,height=5.8cm,ybar,bar width=10pt,",
                r"enlarge x limits=.25,ymin=0,xtick={4,5,7},",
                r"xticklabels={$4\times4$,$5\times5$,$7\times7$},",
                "ylabel={" + ylabel + "},",
                r"tick label style={font=\footnotesize},label style={font=\small},",
                r"ymajorgrids=true,grid style={black!10},",
                r"legend style={at={(.5,-.18)},anchor=north,legend columns=2,",
                r"draw=none,font=\footnotesize}]",
            ]
        )
        for algorithm, color in (
            ("dfs", "pipeblue!75"),
            ("greedy_best_first", "black!40"),
        ):
            coordinates = " ".join(
                f"({size},{summary[algorithm, size][key]})" for size in (4, 5, 7)
            )
            lines.append(
                r"\addplot[fill="
                + color
                + r",draw=none,area legend] coordinates {"
                + coordinates
                + "};"
            )
        lines.extend([r"\legend{DFS,GBFS}", r"\end{axis}\end{tikzpicture}"])
        if key == "time":
            lines.append(r"\hfill")
    (output / "charts.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Built four report tables/charts from 90 verified benchmark rows.")


if __name__ == "__main__":
    main()
